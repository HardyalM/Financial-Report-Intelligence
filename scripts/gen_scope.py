"""Generate scripts/scope.yaml (per-session allowed paths) from docs/MILESTONES.md.

The milestone file is the single source of truth for what each session may touch (gate G2).

Usage:
    python scripts/gen_scope.py           # write scripts/scope.yaml
    python scripts/gen_scope.py --check   # exit 1 if scope.yaml is out of date
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MILESTONES = ROOT / "docs" / "MILESTONES.md"
SCOPE = ROOT / "scripts" / "scope.yaml"

HEADING = re.compile(r"^## (M\d+(?:\.\d+)?) — ")
BACKTICKED = re.compile(r"`([^`]+)`")


def parse(text: str) -> tuple[list[str], dict[str, list[str]]]:
    """Return (global allow-list, {session: allowed globs}) parsed from MILESTONES.md."""
    global_allowed: list[str] = []
    sessions: dict[str, list[str]] = {}
    current: str | None = None
    for line in text.splitlines():
        if line.startswith("| G2 |") and "global allow-list" in line:
            tail = line.split("global allow-list", 1)[1]
            global_allowed = BACKTICKED.findall(tail.split("*(", 1)[0])
        match = HEADING.match(line)
        if match:
            current = match.group(1)
        elif line.startswith("## "):
            current = None
        if current and line.startswith("**Allowed paths:**"):
            sessions[current] = BACKTICKED.findall(line)
    if not global_allowed:
        raise SystemExit("gen_scope: could not find the G2 global allow-list in MILESTONES.md")
    return global_allowed, sessions


def render(global_allowed: list[str], sessions: dict[str, list[str]]) -> str:
    lines = [
        "# GENERATED by scripts/gen_scope.py from docs/MILESTONES.md. Do not edit by hand.",
        "global:",
        *(f'  - "{glob}"' for glob in global_allowed),
        "sessions:",
    ]
    for session, globs in sessions.items():
        lines.append(f'  "{session}":')
        lines.extend(f'    - "{glob}"' for glob in globs)
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate scripts/scope.yaml")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    expected = render(*parse(MILESTONES.read_text(encoding="utf-8")))
    current = SCOPE.read_text(encoding="utf-8") if SCOPE.exists() else ""
    if args.check:
        if current != expected:
            print("scripts/scope.yaml is out of date: run `python scripts/gen_scope.py`")
            return 1
        print("scope.yaml up to date")
        return 0
    if current != expected:
        SCOPE.write_text(expected, encoding="utf-8")
        print("wrote scripts/scope.yaml")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
