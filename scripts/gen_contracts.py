"""Generate typed Pydantic v2 contracts from the locked JSON Schemas.

Standard library only (plus `ruff format` for layout), so it runs offline and in CI.

The JSON Schema is the source of truth (ADR-006). These models are *typed views*:
validation authority stays with the schema (see `finintel.contracts.validate_pack`).
Keywords that only constrain validation (`if`/`then`/`allOf` at the root, conditional
rules) are deliberately not modelled here.

Supported subset: object/properties/required/additionalProperties, $ref to #/$defs,
type (single or list), enum, const, default, array/items, oneOf of simple types,
minimum/maximum/minLength/maxLength/minItems/maxItems/pattern, title, description.

Usage:
    python scripts/gen_contracts.py           # write finintel/contracts/*.py
    python scripts/gen_contracts.py --check   # exit 1 if a generated file is stale
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent

# (schema file, output module, root class name). Later milestones append here.
TARGETS: list[tuple[str, str, str]] = [
    ("schemas/statement_pack.schema.json", "finintel/contracts/statement_pack.py", "StatementPack"),
    ("schemas/ratio_pack.schema.json", "finintel/contracts/ratio_pack.py", "RatioPack"),
    ("schemas/citation.schema.json", "finintel/contracts/citation.py", "Citation"),
    ("schemas/commentary.schema.json", "finintel/contracts/commentary.py", "Commentary"),
    (
        "schemas/reported_metric.schema.json",
        "finintel/contracts/reported_metric.py",
        "ReportedMetric",
    ),
]

HEADER = (
    "# GENERATED by scripts/gen_contracts.py from {schema}. Do not edit by hand.\n"
    "# Run `make contracts` after changing the schema; CI fails if this file is stale.\n"
    "# The JSON Schema is the validation authority; these models are typed views of it.\n"
)

JSON_TO_PY = {"string": "str", "integer": "int", "number": "float", "boolean": "bool"}
CONSTRAINTS = {
    "minimum": "ge",
    "maximum": "le",
    "minLength": "min_length",
    "maxLength": "max_length",
    "minItems": "min_length",
    "maxItems": "max_length",
    "pattern": "pattern",
}


def pascal(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[_\W]+", name) if part)


@dataclass
class ModelClass:
    name: str
    description: str | None
    forbid_extra: bool
    fields: list[str] = field(default_factory=list)


class Generator:
    def __init__(self, schema: dict[str, Any], root_name: str) -> None:
        self.schema = schema
        self.root_name = root_name
        self.classes: dict[str, ModelClass] = {}
        self.order: list[str] = []
        self.needs_literal = False

    # -- type expressions -------------------------------------------------
    def ref_name(self, ref: str) -> str:
        prefix = "#/$defs/"
        if not ref.startswith(prefix):
            raise ValueError(f"unsupported $ref {ref!r}")
        key = ref[len(prefix) :]
        sub = self.schema["$defs"][key]
        name = str(sub.get("title") or pascal(key))
        if name not in self.classes:
            self.build_class(name, sub)
        return name

    def type_expr(self, sub: dict[str, Any], context: str) -> str:
        if "$ref" in sub:
            return self.ref_name(sub["$ref"])
        if "const" in sub:
            self.needs_literal = True
            return f"Literal[{sub['const']!r}]"
        if "oneOf" in sub:
            parts = list(dict.fromkeys(self.type_expr(s, context) for s in sub["oneOf"]))
            parts.sort(key=lambda part: part == "None")  # None last, order otherwise kept
            return " | ".join(parts)
        types = sub.get("type")
        type_list = types if isinstance(types, list) else [types] if types else []
        nullable = "null" in type_list
        if "enum" in sub:
            values = [v for v in sub["enum"] if v is not None]
            nullable = nullable or None in sub["enum"]
            self.needs_literal = True
            expr = "Literal[" + ", ".join(repr(v) for v in values) + "]"
            return f"{expr} | None" if nullable else expr
        concrete = [t for t in type_list if t != "null"]
        parts = [self.single_type(t, sub, context) for t in concrete]
        if not parts:
            parts = ["None"] if nullable else ["Any"]
        elif nullable:
            parts.append("None")
        return " | ".join(parts)

    def single_type(self, json_type: str, sub: dict[str, Any], context: str) -> str:
        if json_type in JSON_TO_PY:
            return JSON_TO_PY[json_type]
        if json_type == "array":
            items = sub.get("items", {})
            if items.get("type") == "object" and "properties" in items:
                name = str(items.get("title") or f"{context}Item")
                self.build_class(name, items)
                return f"list[{name}]"
            return f"list[{self.type_expr(items, context + 'Item')}]"
        if json_type == "object":
            extra = sub.get("additionalProperties")
            props = sub.get("properties", {})
            if isinstance(extra, dict):
                value_type = self.type_expr(extra, context + "Value")
                same = all(self.type_expr(p, context) == value_type for p in props.values())
                if same:
                    return f"dict[str, {value_type}]"
            if props:
                name = str(sub.get("title") or context)
                self.build_class(name, sub)
                return name
            return "dict[str, Any]"
        raise ValueError(f"unsupported type {json_type!r} in {context}")

    # -- classes ----------------------------------------------------------
    def build_class(self, name: str, sub: dict[str, Any]) -> None:
        if name in self.classes:
            return
        cls = ModelClass(name, sub.get("description"), sub.get("additionalProperties") is False)
        self.classes[name] = cls
        required = set(sub.get("required", []))
        for prop, psub in sub.get("properties", {}).items():
            expr = self.type_expr(psub, name + pascal(prop))
            kwargs: list[str] = []
            if prop in required:
                default = None
            elif "default" in psub:
                default = repr(psub["default"])
            else:
                default = "None"
                if "None" not in expr.split(" | "):
                    expr += " | None"
            for key, arg in CONSTRAINTS.items():
                if key in psub:
                    kwargs.append(f"{arg}={psub[key]!r}")
            if "description" in psub:
                kwargs.append(f"description={psub['description']!r}")
            if kwargs:
                first = "..." if default is None else default
                line = f"    {prop}: {expr} = Field({', '.join([first, *kwargs])})"
            elif default is None:
                line = f"    {prop}: {expr}"
            else:
                line = f"    {prop}: {expr} = {default}"
            cls.fields.append(line)
        self.order.append(name)  # dependencies are appended before their users

    # -- output -----------------------------------------------------------
    def render(self, schema_path: str) -> str:
        self.build_class(self.root_name, self.schema)
        uses_any = any(
            re.search(r"\bAny\b", line) for cls in self.classes.values() for line in cls.fields
        )
        typing_imports = (["Any"] if uses_any else []) + (["Literal"] if self.needs_literal else [])
        out = [
            HEADER.format(schema=schema_path),
            "from __future__ import annotations\n",
            f"from typing import {', '.join(typing_imports)}\n" if typing_imports else "",
            "from pydantic import BaseModel, ConfigDict, Field\n",
            "__all__ = [" + ", ".join(repr(n) for n in self.order) + "]\n",
        ]
        for name in self.order:
            cls = self.classes[name]
            body = [f"class {name}(BaseModel):"]
            if cls.description:
                body.append(f'    """{cls.description}"""')
            if cls.forbid_extra:
                body.append('    model_config = ConfigDict(extra="forbid")')
            body.extend(cls.fields or ["    pass"])
            out.append("\n\n" + "\n".join(body) + "\n")
        return "\n".join(out)


def ruff_format(source: str) -> str:
    ruff = shutil.which("ruff")
    if ruff is None:
        sys.exit("gen_contracts: `ruff` is required (it is a dev dependency; run `uv sync`).")
    proc = subprocess.run(
        [ruff, "format", "--stdin-filename", "contracts.py", "-"],
        input=source,
        capture_output=True,
        text=True,
        check=True,
        cwd=ROOT,
    )
    return proc.stdout


def generate(schema_rel: str, root_name: str) -> str:
    schema = json.loads((ROOT / schema_rel).read_text(encoding="utf-8"))
    return ruff_format(Generator(schema, root_name).render(schema_rel))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args(argv)
    stale: list[str] = []
    for schema_rel, out_rel, root_name in TARGETS:
        code = generate(schema_rel, root_name)
        out = ROOT / out_rel
        current = out.read_text(encoding="utf-8") if out.exists() else None
        if args.check:
            if current != code:
                stale.append(out_rel)
        elif current != code:
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(code, encoding="utf-8")
            print(f"wrote {out_rel}")
    if stale:
        print("Stale generated contracts (run `make contracts`): " + ", ".join(stale))
        return 1
    if args.check:
        print("contracts up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
